"""FUSE VALLEY — writes art/props/studio_import_lobby.luau from the lobby props' manifests and upload ids.

Covers Crate.Inferno and Crate.GiftBox (→ ReplicatedStorage.FV_Art.Crates.<Kind>, with the Hinge attachment the crate
opening uses) and Prop.CrateStand / Prop.SpinWheel / Prop.Podium (→ FV_Art.Props.<Name>, with the spots the game reads:
CrateSpot on the stand, Axle + PointerPin on the wheel, Spot1..3 on the podium). Run after every re-upload:

    python -I art/props/gen_lobby_import.py
"""

import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "art", "out")
KEYS = ["Crate.Inferno", "Crate.GiftBox", "Prop.CrateStand", "Prop.SpinWheel", "Prop.Podium"]


def v3(t):
    return "Vector3.new(%g, %g, %g)" % tuple(round(x, 4) + 0.0 for x in t)


def entry(key):
    m = json.load(open(os.path.join(OUT, key, "manifest.json")))
    model = json.load(open(os.path.join(OUT, key, "export", "ids.json")))[key]
    tex = json.load(open(os.path.join(OUT, key, "export", "textures", "ids.json")))
    prefix = key.replace(".", "_") + "_"
    maps = {}
    for part in m["parts"]:
        ids = [tex.get(prefix + part + "_" + kind) for kind in ("COLOR", "ROUGHNESS", "NORMAL", "METAL")]
        if all(ids):
            maps[part] = ids
    kind, name = key.split(".")
    folder = "Crates" if kind == "Crate" else "Props"
    spots = {}
    if "hinge_roblox_from_pivot" in m:
        spots["Hinge"] = m["hinge_roblox_from_pivot"]
    if "crate_spot_roblox_from_pivot" in m:
        spots["CrateSpot"] = m["crate_spot_roblox_from_pivot"]
    if "disc" in m:
        spots["Axle"] = m["disc"]["axle_roblox_from_pivot"]
        spots["PointerPin"] = m["pointer"]["pin_roblox_from_pivot"]
    for r, s in (m.get("spots") or {}).items():
        spots["Spot" + r] = s["roblox_from_pivot"]
    lines = ["\t%s = {" % name, '\t\tfolder = "%s",' % folder, "\t\tmodel = %s," % model, "\t\tmaps = {"]
    for part, ids in maps.items():
        lines.append("\t\t\t%s = { %s }," % (part, ", ".join(ids)))
    lines.append("\t\t},")
    lines.append("\t\tglow = {")
    for part, hexc in (m.get("glow_colors") or {}).items():
        lines.append('\t\t\t%s = Color3.fromHex("%s"),' % (part, hexc))
    lines.append("\t\t},")
    lines.append("\t\tspots = {")
    for sname, p in spots.items():
        lines.append("\t\t\t%s = %s," % (sname, v3(p)))
    lines.append("\t\t},")
    lines.append("\t},")
    return "\n".join(lines)


HEAD = '''--!strict
-- FUSE VALLEY — Studio import for the lobby props (generated by art/props/gen_lobby_import.py; do not hand-edit).
-- Run in the EDIT data model. Builds ReplicatedStorage.FV_Art.Crates.Inferno / GiftBox (MeshParts with SurfaceAppearance
-- PBR, Neon glow parts, the Hinge attachment on BodyWood the crate opening swings the lid about) and FV_Art.Props.
-- CrateStand / SpinWheel / Podium (the spots as Attachments on the model's first part: CrateSpot, Axle + PointerPin,
-- Spot1..3). Every part is decorative; the pivot is the bottom centre (the manifests measure spots from it).

local ITEMS: { [string]: any } = {
'''

TAIL = '''}

local IS = game:GetService("InsertService")
local cache: { [string]: string } = {}
local function texOf(id: string): string
	if cache[id] then
		return cache[id]
	end
	local a = IS:LoadAsset(tonumber(id) :: number)
	local d = a:FindFirstChildWhichIsA("Decal", true)
	local t = if d then d.Texture else ("rbxassetid://" .. id)
	a:Destroy()
	cache[id] = t
	return t
end

local art = game.ReplicatedStorage:FindFirstChild("FV_Art") :: Folder
local report = {}
for name, it in pairs(ITEMS) do
	local imp = IS:LoadAsset(it.model)
	local model = Instance.new("Model")
	model.Name = name
	for _, d in imp:GetDescendants() do
		if d:IsA("MeshPart") then
			d.Name = (d.Name:gsub("%.%d+$", ""))
			d.Parent = model
		end
	end
	imp:Destroy()
	model.WorldPivot = CFrame.new()
	model:ScaleTo(0.01)
	local cf, size = model:GetBoundingBox()
	model.WorldPivot = CFrame.new(cf.Position - Vector3.new(0, size.Y / 2, 0))
	local first: BasePart? = nil
	for _, p in model:GetChildren() do
		if not p:IsA("MeshPart") then
			continue
		end
		p.Anchored, p.CanCollide, p.CanQuery, p.CanTouch, p.Massless = true, false, false, false, true
		local glow = it.glow[p.Name]
		if glow then
			p.Material = Enum.Material.Neon
			p.Color = glow
			p.CastShadow = false
		else
			p.Material = Enum.Material.SmoothPlastic
			p.Color = Color3.new(1, 1, 1)
			local ids = it.maps[p.Name]
			if ids then
				local sa = Instance.new("SurfaceAppearance")
				sa.ColorMap = texOf(ids[1])
				sa.RoughnessMap = texOf(ids[2])
				sa.NormalMap = texOf(ids[3])
				sa.MetalnessMap = texOf(ids[4])
				sa.Parent = p
			end
			first = first or p
		end
	end
	local holder = (model:FindFirstChild("BodyWood") or first) :: BasePart
	for sname, at in pairs(it.spots) do
		local a = Instance.new("Attachment")
		a.Name = sname
		a.Parent = holder
		a.WorldPosition = model.WorldPivot:PointToWorldSpace(at)
	end
	local folder = art:FindFirstChild(it.folder) or Instance.new("Folder")
	folder.Name = it.folder
	folder.Parent = art
	local old = folder:FindFirstChild(name)
	if old then
		old:Destroy()
	end
	model.Parent = folder
	local _, sz = model:GetBoundingBox()
	table.insert(report, ("%s/%s %d parts %s"):format(it.folder, name, #model:GetChildren(), tostring(sz)))
end
return table.concat(report, "; ")
'''


def main():
    body = "\n".join(entry(k) for k in KEYS)
    path = os.path.join(ROOT, "art", "props", "studio_import_lobby.luau")
    open(path, "w", encoding="utf-8", newline="\n").write(HEAD + body + "\n" + TAIL)
    print("wrote", path)


main()
